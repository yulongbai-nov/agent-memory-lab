'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const {openArchive} = require('../lib/archive.cjs');
const {originalCapture,verifyOriginal} = require('../lib/originals.cjs');
const {Client} = require('@modelcontextprotocol/sdk/client/index.js');
const {StdioClientTransport} = require('@modelcontextprotocol/sdk/client/stdio.js');

test('JSON migration preserves evidence, checkpoint, scope and read-only MCP projection', async t => {
  const dir=await fs.mkdtemp(path.join(os.tmpdir(),'memory-sqlite-integration-'));
  t.after(()=>fs.rm(dir,{recursive:true,force:true}));
  const scope={owner:'synthetic',project:'migration'}, source={harness:'test',instance:'one',session:'s'};
  const archived=await originalCapture(dir)({bytes:Buffer.from('{"text":"synthetic original"}\n'),coordinate:1});
  const before=await openArchive({dir});
  await before.importBatch({scope,source,checkpoint:{position:1},items:[{id:'one',kind:'message',text:'synthetic evidence',metadata:{original:archived}}]});
  const original=await before.getItem({...scope,id:'one'});
  await before.addAnnotation({id:'review',scope,kind:'decision',text:'Reviewed choice',topic:'Migration',target:{id:'one',revision:original.versionId,source}});
  const jsonPath=path.join(dir,'archive.json'), jsonBefore=await fs.readFile(jsonPath);
  const {migrateJsonToSqlite}=require('../lib/storage-sqlite.cjs');
  await migrateJsonToSqlite({dir});
  assert.deepEqual(await fs.readFile(jsonPath),jsonBefore);
  await assert.rejects(migrateJsonToSqlite({dir}));
  const after=await openArchive({dir});
  const retrieved=await after.getItem({...scope,id:'one',revision:original.versionId});
  assert.deepEqual(retrieved,original);
  assert.deepEqual(retrieved.item.metadata.original,archived);
  assert.equal((await verifyOriginal(dir,retrieved.item.metadata.original)).verified,true);
  assert.equal((await after.getCheckpoint({...scope,...source})).position,1);
  await after.importBatch({scope,source,checkpoint:{previous:1,position:2},items:[{id:'two',kind:'message',text:'new evidence'}]});
  const second=await after.getItem({...scope,id:'two'});
  await after.addAnnotation({id:'next',scope,kind:'todo',text:'Next step',topic:'Migration',target:{id:'two',revision:second.versionId,source}});
  assert.equal((await after.getCheckpoint({...scope,...source})).position,2);
  assert.equal((await after.listAnnotations(scope)).length,2);
  assert.deepEqual(await after.listItems({owner:'synthetic',project:'other'}),[]);
  assert.equal(await after.getItem({owner:'synthetic',project:'other',id:'one',revision:original.versionId}),null);
  await assert.rejects(after.addAnnotation({id:'outside',scope:{owner:'synthetic',project:'other'},kind:'note',text:'wrong scope',target:{id:'one',revision:original.versionId,source}}));
  assert.deepEqual(await fs.readFile(jsonPath),jsonBefore);
  const transport=new StdioClientTransport({command:process.execPath,args:[path.join(__dirname,'../bin/memory.cjs'),'mcp','--dir',dir,'--owner',scope.owner,'--project',scope.project],stderr:'pipe'});
  const client=new Client({name:'synthetic-sqlite-check',version:'1'}); t.after(()=>client.close());
  await client.connect(transport);
  const tools=await client.listTools(); assert(!tools.tools.some(x=>x.name==='memory_annotate'));
  const current=await client.callTool({name:'memory_current',arguments:{topic:'Migration'}});
  assert.equal(current.isError,undefined); assert.match(current.content[0].text,/Reviewed choice/);
  const evidence=await client.callTool({name:'memory_evidence',arguments:{id:'one',revision:original.versionId}});
  assert.equal(evidence.isError,undefined);
  assert.deepEqual(JSON.parse(evidence.content[0].text).original,archived);
  assert(!evidence.content[0].text.includes('synthetic original'));
  assert.deepEqual(await fs.readFile(jsonPath),jsonBefore);
});

test('read-only CLI reports a missing archive without creating it', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(),'memory-sqlite-missing-'));
  t.after(() => fs.rm(root,{recursive:true,force:true}));
  const dir = path.join(root,'not-created');
  const {spawnSync} = require('node:child_process');
  const run = spawnSync(process.execPath,[path.join(__dirname,'../bin/memory.cjs'),'find','--dir',dir,'--project','synthetic'],{encoding:'utf8'});
  assert.notEqual(run.status,0);
  assert.match(run.stderr,/No local archive directory/);
  await assert.rejects(fs.stat(dir),{code:'ENOENT'});
});
